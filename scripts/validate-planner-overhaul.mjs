import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const exists = (p) => fs.existsSync(path.join(root, p))
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const database = read('src/db/database.ts')
const dates = read('src/domain/date.ts')
const hook = read('src/hooks/usePlannerData.ts')
const planner = read('src/features/planner/PlannerView.tsx')
const views = read('src/features/planner/PlannerOverhaulViews.tsx')
const logic = read('src/features/planner/plannerLogic.ts')
const calendar = read('src/features/planner/CalendarView.tsx')
const styles = read('src/styles/index.css')

check('v1.4+ package version', Number(pkg.version.split('.')[1] ?? 0) >= 4)
check('planner validator registered', pkg.scripts?.['validate:planner'] === 'node scripts/validate-planner-overhaul.mjs')
check('release gate runs planner validation', pkg.scripts?.['release:verify']?.includes('validate:planner'))
check('planner-compatible schema', Number(database.match(/DATABASE_SCHEMA_VERSION\s*=\s*(\d+)/)?.[1] ?? 0) >= 13)
check('month date helpers exist', dates.includes('addLocalMonths') && dates.includes('startOfLocalMonth') && dates.includes('localMonthGrid'))
check('planner hook exposes selected day', hook.includes('selectedDay') && hook.includes('selectedDate'))
check('planner hook exposes 42-day month', hook.includes('monthDays') && hook.includes('localMonthGrid'))
check('planner hook exposes unified backlog', hook.includes('backlog') && hook.includes('weekUnplannedDue'))
check('day summaries separate deadlines', logic.includes('deadlines: TaskPreview[]') && logic.includes('dueOpenTasks'))
check('week placement respects deadline', logic.includes('suggestWeekPlacement') && logic.includes('day.date <= task.deadline'))
check('six planner modes registered', ["'agenda'", "'day'", "'week'", "'month'", "'calendar'", "'advanced'"].every((value) => planner.includes(value)))
check('planner preserves selected date across modes', planner.includes('selectedDate') && planner.includes('anchorDate={selectedDate}') && planner.includes('onSelectedDateChange={setSelectedDate}'))
check('day planner renders capacity and deadline lane', views.includes('planner-day-summary') && views.includes('Deadline lane'))
check('week planner exposes backlog and weekly decisions', views.includes('Plan this week') && views.includes('planner-week-shell') && views.includes('BacklogSidebar'))
check('month planner uses 42-day workload grid', views.includes('planner-month-grid') && views.includes('Workload and deadline map'))
check('planner visibly distinguishes planned date and deadline', views.includes('Planned = intended work date') && views.includes('Deadline = must be finished by'))
check('planner drag changes planned date', views.includes("setData('text/task-id'") && views.includes('onMoveDate(id, date)'))
check('planner keyboard rescheduling exists', views.includes("event.key === 'ArrowLeft'") && views.includes("event.key === 'ArrowRight'") && views.includes("event.key === 'Backspace'"))
check('calendar accepts planner anchor date', calendar.includes('anchorDate') && calendar.includes('onSelectedDateChange'))
check('planner overhaul stylesheet loaded', styles.includes("@import './planner-overhaul.css';"))
check('v1.4 release doc exists', exists('docs/PLANNER_OVERHAUL_V1_4.md'))

const failures = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'}  ${item.name}`)
console.log(`\n${checks.length - failures.length}/${checks.length} planner-overhaul checks passed.`)
if (failures.length) process.exit(1)
