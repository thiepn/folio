import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const exists = (p) => fs.existsSync(path.join(root, p))
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const models = read('src/domain/models.ts')
const schemas = read('src/domain/schemas.ts')
const database = read('src/db/database.ts')
const migration = read('src/migrations/v15ToV16.ts')
const repository = read('src/repositories/taskRepository.ts')
const service = read('src/services/taskService.ts')
const inspector = read('src/features/tasks/TaskInspector.tsx')
const adapters = read('src/adapters/uiAdapters.ts')
const appData = read('src/hooks/useAppData.ts')
const app = read('src/app/App.tsx')
const backupSchemas = read('src/services/backupSchemas.ts')
const interop = read('src/features/interop/InteroperabilityModal.tsx')
const styles = read('src/styles/index.css')

check('Task Engine V2 validator registered', pkg.scripts?.['validate:task-v2'] === 'node scripts/validate-task-engine-v2.mjs')
check('release gate runs Task Engine V2 validation', pkg.scripts?.['release:verify']?.includes('validate:task-v2'))
check('Task Engine V2 remains schema-compatible', Number(database.match(/DATABASE_SCHEMA_VERSION\s*=\s*(\d+)/)?.[1] ?? 0) >= 16 && database.includes('this.version(16)'))
check('v15 to v16 task migration registered', database.includes('migrateV15ToV16') && migration.includes("task.tags") && migration.includes("task.checklist") && migration.includes("task.comments"))
check('task model has rich execution fields', ['tags: string[]','checklist: TaskChecklistItem[]','progressMode: TaskProgressMode','progressPercent: number','sourceUrl?: string','location?: string','pinned: boolean','comments: TaskComment[]','activity: TaskActivityEntry[]'].every((token) => models.includes(token)))
check('task schemas validate rich execution fields', ['taskChecklistItemSchema','taskCommentSchema','taskProgressModeSchema','tags: taskTagsSchema','progressPercent: z.number().int().min(0).max(100)','sourceUrl: z.string().trim().url()','comments: z.array(taskCommentSchema)'].every((token) => schemas.includes(token)))
check('repository initializes and normalizes Task V2 data', repository.includes('normalizeTags') && repository.includes("label: 'Task created'") && repository.includes('activity: appendActivity'))
check('nested task traversal is recursive', service.includes('const queue =') && service.includes('queue.push(...(byParent.get(next.id) ?? []))'))
check('old one-level nested-task ceiling removed', !service.includes('Nested subtasks are intentionally limited to one level.'))
check('deleted subtrees can be restored recursively', service.includes('descendants(id, true)') && service.includes("'restored'"))
check('tree duplication remaps parent IDs', service.includes('const idMap = new Map') && service.includes('parentTaskId: task.parentTaskId ? idMap.get(task.parentTaskId)'))
check('tree duplication regenerates checklist IDs', service.includes('cloneChecklist') && service.includes('id: crypto.randomUUID()'))
check('preview derives automatic progress', adapters.includes('automaticProgress') && adapters.includes('completedUnits / progressUnits'))
check('nested previews retain child counts', appData.includes('childMap.get(task.id) ?? []'))
check('nested tasks can be opened in inspector', app.includes('data?.subtasks.find') && app.includes('onOpenSubtask={(id) => setSelectedTaskId(id)}'))
check('task inspector exposes tags', inspector.includes('task-v2-context-section') && inspector.includes('parseTags'))
check('task inspector exposes checklist', inspector.includes('task-v2-checklist-section') && inspector.includes('toggleChecklistItem'))
check('task inspector exposes progress modes', inspector.includes('task-v2-progress-section') && inspector.includes("progressMode === 'manual'"))
check('task inspector exposes URL and location', inspector.includes('type="url"') && inspector.includes('setLocation'))
check('task inspector exposes pinning', inspector.includes('task-pin-toggle') && inspector.includes('setPinned'))
check('task inspector exposes comments and activity', inspector.includes('task-v2-comments-section') && inspector.includes('task-v2-activity-section'))
check('task inspector exposes unlimited nested work', inspector.includes('unlimited depth') && inspector.includes('onOpenSubtask'))
check('backup parser preserves Task V2 fields', ['tags: z.array(z.string()).default([])','checklist: z.array(backupTaskChecklistItemSchema).default([])','progressMode: z.enum([\'auto\',\'manual\']).default(\'auto\')','comments: z.array(backupTaskCommentSchema).default([])','activity: z.array(backupTaskActivitySchema).default([])'].every((token) => backupSchemas.includes(token)))
check('public v16 backup schema exists', exists('public/schema/folio-backup-v16.schema.json'))
check('interop retains v16 restore compatibility', interop.includes('Schema v21 · complete planner state + rich content') && interop.includes('schema v8–v21'))
check('Task Engine V2 stylesheet loaded', styles.includes("@import './task-engine-v2.css';"))
check('Task Engine V2 design document exists', exists('docs/TASK_ENGINE_V2_D1.md'))

const failures = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'}  ${item.name}`)
console.log(`\n${checks.length - failures.length}/${checks.length} Task Engine V2 checks passed.`)
if (failures.length) process.exit(1)
