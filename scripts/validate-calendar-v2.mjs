const temp=fs.mkdtempSync(path.join(os.tmpdir(),'folio-calendar-v2-'))
try{
  const options={compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}
  const transpile=(source)=>ts.transpileModule(source,options).outputText
  fs.writeFileSync(path.join(temp,'date.mjs'),transpile(date),'utf8')
  const logicSource=logic.replace("../../domain/date","./date.mjs")
  fs.writeFileSync(path.join(temp,'calendarLogic.mjs'),transpile(logicSource),'utf8')
  const caseSource=cases.replace("./calendarLogic","./calendarLogic.mjs")
  fs.writeFileSync(path.join(temp,'calendarCases.mjs'),transpile(caseSource),'utf8')
  const runtime=await import(pathToFileURL(path.join(temp,'calendarCases.mjs')).href+'?v='+Date.now())
  const failures=runtime.validateCalendarLogicCases()
  check('actual D7 calendar logic case matrix passes',Array.isArray(failures)&&failures.length===0)
  if(failures.length) console.log('D7 calendar logic failures:',failures)

  const icsSource=ics.replace("../../domain/date","./date.mjs")
  fs.writeFileSync(path.join(temp,'icsLogic.mjs'),transpile(icsSource),'utf8')
  const icsCaseSource=icsCases.replace("../../domain/date","./date.mjs").replace("./icsLogic","./icsLogic.mjs")
  fs.writeFileSync(path.join(temp,'icsCases.mjs'),transpile(icsCaseSource),'utf8')
  const icsRuntime=await import(pathToFileURL(path.join(temp,'icsCases.mjs')).href+'?v='+Date.now())
  const icsFailures=icsRuntime.validateIcsCalendarV2Cases()
  check('actual D7 ICS case matrix passes',Array.isArray(icsFailures)&&icsFailures.length===0)
  if(icsFailures.length) console.log('D7 ICS failures:',icsFailures)
}catch(error){
  console.log('D7 runtime validation error:',error)
  check('actual D7 calendar logic case matrix passes',false)
  check('actual D7 ICS case matrix passes',false)
}finally{
  fs.rmSync(temp,{recursive:true,force:true})
}

const failures=checks.filter((item)=>!item.ok)
