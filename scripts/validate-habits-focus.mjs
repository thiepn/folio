import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const exists = (p) => fs.existsSync(path.join(root, p))
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const models = read('src/domain/models.ts')
const schemas = read('src/domain/schemas.ts')
const database = read('src/db/database.ts')
const migration = read('src/migrations/v14ToV15.ts')
const habitLogic = read('src/domain/habit.ts')
const habitHook = read('src/hooks/useHabitData.ts')
const habitsView = read('src/features/habits/HabitsView.tsx')
const habitDetail = read('src/features/habits/HabitDetailDrawer.tsx')
const habitService = read('src/services/habitService.ts')
const focusPlanning = read('src/features/focus/focusPlanning.ts')
const focusOverlay = read('src/features/focus/FocusOverlay.tsx')
const focusService = read('src/services/focusService.ts')
const focusRepo = read('src/repositories/focusSessionRepository.ts')
const history = read('src/features/review/historyLogic.ts')
const backupSchemas = read('src/services/backupSchemas.ts')
const app = read('src/app/App.tsx')
const styles = read('src/styles/index.css')
const interop = read('src/features/interop/InteroperabilityModal.tsx')

check('v1.6+ package version', Number(pkg.version.split('.')[1] ?? 0) >= 6)
check('habits-focus validator registered', pkg.scripts?.['validate:habits-focus'] === 'node scripts/validate-habits-focus.mjs')
check('release gate runs habits-focus validation', pkg.scripts?.['release:verify']?.includes('validate:habits-focus'))
check('database schema remains v15-compatible', Number(database.match(/DATABASE_SCHEMA_VERSION\s*=\s*(\d+)/)?.[1] ?? 0) >= 15)
check('v14 to v15 migration registered', database.includes('migrateV14ToV15') && database.includes('this.version(15)'))
check('migration backfills pause history', migration.includes('habit.pauses = []'))
check('habit model stores pause periods', models.includes('export interface HabitPausePeriod') && models.includes('pauses: HabitPausePeriod[]'))
check('focus model stores plan and reflection', models.includes('plannedSeconds?: number') && models.includes('intention?: string') && models.includes('note?: string'))
check('habit schema defaults pauses', schemas.includes('pauses: z.array(habitPausePeriodSchema).default([])'))
check('focus schema accepts optional plan and intention', schemas.includes('plannedSeconds:') && schemas.includes('intention:') && schemas.includes('note:'))
check('habit schedules exclude paused dates', habitLogic.includes('habitPausedForDate(habit, date)') && habitLogic.includes('if (habitPausedForDate(habit, date)) return false'))
check('habit streak treats pause as neutral', habitLogic.includes("if (habitPausedForDate(habit, date)) { date = addLocalDays(date, -1); continue }"))
check('habit adherence excludes pauses', habitLogic.includes('flexibleTargetForRange') && habitLogic.includes(".filter((date) => !habitPausedForDate(habit, date))"))
check('habit weekly trend exists', habitLogic.includes('habitWeeklyTrend') && habitDetail.includes('8-week trend'))
check('habit previews expose paused state', habitHook.includes('paused,') && habitHook.includes('pauseLabel: habitPauseLabel'))
check('habit service can pause', habitService.includes('async pause(') && habitService.includes('HabitPausePeriod'))
check('habit service can resume with undo', habitService.includes('async resume(') && habitService.includes("message: 'Habit resumed'") && habitService.includes('undo: async'))
check('paused habit logging is blocked', habitService.includes('Resume it before logging progress'))
check('habits screen has week check and pause count', habitsView.includes('Week check') && habitsView.includes('pausedCount'))
check('habit detail has lifecycle pause controls', habitDetail.includes('Pause without losing history') && habitDetail.includes('Resume rhythm'))
check('focus ranking excludes blockers', focusPlanning.includes('rankFocusTasks') && focusPlanning.includes('activeBlockerCount'))
check('focus suggestion is explained', focusPlanning.includes('focusTaskReason') && focusOverlay.includes('Why this work'))
check('focus launcher accepts intention', focusOverlay.includes('Session intention') && focusOverlay.includes('intention.trim()'))
check('stopwatch supports optional session plan', focusOverlay.includes('Optional session plan') && focusOverlay.includes('guidance'))
check('focus session captures finish note', focusOverlay.includes('Session note') && focusService.includes('note?.trim()'))
check('focus service persists plan and intention', focusService.includes('plannedSeconds: plannedSeconds') && focusService.includes('intention: intention?.trim()'))
check('focus repository persists context', focusRepo.includes('plannedSeconds: parsed.plannedSeconds') && focusRepo.includes('intention: parsed.intention') && focusRepo.includes('note: parsed.note'))
check('focus launcher exposes weekly context and recent history', focusOverlay.includes('This week') && focusOverlay.includes('Recent sessions'))
check('history indexes focus intention and note', history.includes('session.intention') && history.includes('session.note'))
check('backup schemas preserve v15 habit/focus fields', backupSchemas.includes('pauses:') && backupSchemas.includes('plannedSeconds:') && backupSchemas.includes('intention:') && backupSchemas.includes('note:'))
check('app wires pause/resume and richer focus callbacks', app.includes('habitService.pause') && app.includes('habitService.resume') && app.includes('plannedSeconds') && app.includes('weekSessionCount'))
check('public v15 backup schema exists', exists('public/schema/folio-backup-v15.schema.json'))
check('interop retains v15 restore compatibility', interop.includes('Schema v20 · complete planner state') && interop.includes('schema v8–v20'))
check('habits-focus stylesheet loaded', styles.includes("@import './habits-focus.css';"))
check('v1.6 release doc exists', exists('docs/HABITS_FOCUS_V1_6.md'))

const failures = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'}  ${item.name}`)
console.log(`\n${checks.length - failures.length}/${checks.length} habits-focus checks passed.`)
if (failures.length) process.exit(1)
