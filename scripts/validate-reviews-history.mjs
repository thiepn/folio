import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const exists = (p) => fs.existsSync(path.join(root, p))
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const models = read('src/domain/models.ts')
const schemas = read('src/domain/schemas.ts')
const database = read('src/db/database.ts')
const backup = read('src/services/backupService.ts')
const backupSchemas = read('src/services/backupSchemas.ts')
const service = read('src/services/reviewRecordService.ts')
const repository = read('src/repositories/reviewRecordRepository.ts')
const history = read('src/features/review/historyLogic.ts')
const historyHook = read('src/hooks/useHistoryData.ts')
const reviewView = read('src/features/review/ReviewView.tsx')
const workflow = read('src/features/review/ReviewWorkflowModal.tsx')
const app = read('src/app/App.tsx')
const styles = read('src/styles/index.css')
const interop = read('src/features/interop/InteroperabilityModal.tsx')

check('v1.5+ package version', Number(pkg.version.split('.')[1] ?? 0) >= 5)
check('reviews-history validator registered', pkg.scripts?.['validate:reviews-history'] === 'node scripts/validate-reviews-history.mjs')
check('release gate runs reviews-history validation', pkg.scripts?.['release:verify']?.includes('validate:reviews-history'))
check('reviews-compatible schema', Number(database.match(/DATABASE_SCHEMA_VERSION\s*=\s*(\d+)/)?.[1] ?? 0) >= 14)
check('v13 to v14 migration registered', database.includes('migrateV13ToV14') && database.includes('this.version(14)'))
check('reviewRecords table declared', database.includes('reviewRecords!: Table<ReviewRecordEntity') && database.includes("reviewRecords: '&id,kind,periodStart,periodEnd,updatedAt,[kind+periodStart]'"))
check('review record model exists', models.includes("export type ReviewKind = 'daily' | 'weekly' | 'monthly'") && models.includes('export interface ReviewRecordEntity') && models.includes('ReviewRecordMetrics'))
check('review record schema exists', schemas.includes('reviewKindSchema') && schemas.includes('reviewRecordSchema'))
check('one record per kind/period lookup exists', repository.includes("where('[kind+periodStart]')") && repository.includes('getForPeriod'))
check('review save snapshots metrics', service.includes('computeMetrics') && service.includes('completedPlannedTasks') && service.includes('completedMilestones'))
check('daily wrap-up is durable', app.includes('reviewRecordService.saveDailySummary'))
check('weekly workflow saves reflection', workflow.includes('WeeklyReviewReflection') && workflow.includes('Save review & plan next week') && app.includes('onSaveReview'))
check('monthly review editor exists', exists('src/features/review/ReviewRecordModal.tsx') && reviewView.includes("onNewReview('monthly')"))
check('review page has three surfaces', reviewView.includes("type ReviewTab = 'week' | 'reviews' | 'history'") && reviewView.includes('Saved reviews') && reviewView.includes('History'))
check('week has what actually happened section', reviewView.includes('What actually happened') && reviewView.includes('historyCounts'))
check('plan vs actual remains explicit', reviewView.includes('Plan vs actual') && reviewView.includes('Scheduled, estimated, actual'))
check('history includes canonical event types', history.includes("'task' | 'focus' | 'habit' | 'project' | 'review'") && history.includes('buildHistoryEvents'))
check('history is searchable/filterable', history.includes('filterHistoryEvents') && reviewView.includes('Search history') && reviewView.includes('All history'))
check('history hook uses repositories', historyHook.includes('taskRepository.listSnapshot') && historyHook.includes('reviewRecordRepository.listAll'))
check('v14 backup includes review records', backup.includes('reviewRecords: ReviewRecordEntity[]') && backup.includes("'reviewRecords'"))
check('legacy backups default review records empty', schemas.includes('reviewRecords: z.array(z.unknown()).default([])'))
check('backup parser preserves v13 project workflow fields', backupSchemas.includes('nextActionTaskId') && backupSchemas.includes('milestones') && backupSchemas.includes('activity') && backupSchemas.includes('notes:'))
check('public v14 backup schema exists', exists('public/schema/folio-backup-v14.schema.json'))
check('interop retains v14 restore compatibility', interop.includes('schema v8–v24'))
check('reviews-history stylesheet loaded', styles.includes("@import './reviews-history.css';"))
check('v1.5 release doc exists', exists('docs/REVIEWS_HISTORY_V1_5.md'))

const failures = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'}  ${item.name}`)
console.log(`\n${checks.length - failures.length}/${checks.length} reviews-history checks passed.`)
if (failures.length) process.exit(1)
