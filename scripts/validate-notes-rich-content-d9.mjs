import fs from 'node:fs'
import path from 'node:path'

const root=process.cwd()
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8')
const exists=(p)=>fs.existsSync(path.join(root,p))
const checks=[]
const check=(name,ok)=>checks.push({name,ok:Boolean(ok)})

const pkg=JSON.parse(read('package.json'))
const models=read('src/domain/models.ts')
const schemas=read('src/domain/schemas.ts')
const database=read('src/db/database.ts')
const migration=read('src/migrations/v20ToV21.ts')
const notes=read('src/features/content/NotesView.tsx')
const editor=read('src/features/content/MarkdownEditor.tsx')
const renderer=read('src/features/content/SafeMarkdown.tsx')
const attachments=read('src/features/content/AttachmentPanel.tsx')
const attachmentService=read('src/services/attachmentService.ts')
const search=read('src/services/contentSearchService.ts')
const backup=read('src/services/backupService.ts')
const selective=read('src/services/selectiveExportService.ts')
const inspector=read('src/features/tasks/TaskInspector.tsx')
const app=read('src/app/App.tsx')
const sidebar=read('src/components/layout/Sidebar.tsx')
const styles=read('src/styles/index.css')

check('D9 validator registered',pkg.scripts?.['validate:d9']==='node scripts/validate-notes-rich-content-d9.mjs')
check('release gate runs D9 validation',pkg.scripts?.['release:verify']?.includes('validate:d9'))
check('database schema v21',/DATABASE_SCHEMA_VERSION\s*=\s*21\b/.test(database)&&database.includes('this.version(21)'))
check('v20 to v21 migration registered',database.includes('migrateV20ToV21')&&migration.includes('searchDocuments'))
check('standalone Note model exists',models.includes('interface NoteEntity')&&models.includes("ContentOwnerType = 'task' | 'note'"))
check('attachments store local Blob data',models.includes('interface AttachmentEntity')&&models.includes('blob?: Blob'))
check('search index is persisted separately',models.includes('interface SearchDocumentEntity')&&database.includes('searchDocuments:'))
check('task Markdown capacity expanded',schemas.includes("description: z.string().max(100_000)"))
check('standalone note schema exists',schemas.includes('noteCreateSchema')&&schemas.includes('noteUpdateSchema'))
check('safe renderer never uses raw HTML injection',renderer.includes('SafeMarkdown')&&!renderer.includes('dangerouslySetInnerHTML'))
check('renderer supports headings lists quotes code and checkboxes',['heading','<ul','<ol','<blockquote','<pre','markdown-checkbox'].every((token)=>renderer.includes(token)))
check('Markdown editor exposes edit and reading modes',editor.includes("'edit' | 'read'")&&editor.includes('Reading'))
check('task inspector uses rich Markdown and attachments',inspector.includes('<MarkdownEditor')&&inspector.includes('<AttachmentPanel')&&inspector.includes('createFromTask'))
check('standalone Notes workspace exists',notes.includes('export function NotesView')&&notes.includes('Note → inbox task'))
check('archived Notes are recoverable',notes.includes('Archived notes')&&notes.includes('Restore')&&notes.includes('Delete permanently')&&notes.includes('Search archived notes'))
check('desktop navigation exposes Notes',sidebar.includes("view: 'notes'"))
check('App routes Notes workspace',app.includes("view === 'notes'")&&app.includes('<NotesView'))
check('drag drop and paste attachments supported',attachments.includes('onDrop=')&&attachments.includes('onPaste='))
check('attachments can open download and remove',attachments.includes('openAttachment')&&attachments.includes('downloadAttachment')&&attachments.includes('attachmentService.remove'))
check('quota pressure checked before writes',attachmentService.includes('navigator.storage')&&attachmentService.includes('QUOTA_HEADROOM_BYTES')&&attachmentService.includes('assertBatchQuota'))
check('multi-file attachment writes are atomic',attachmentService.includes("db.transaction('rw', db.attachments")&&attachmentService.includes('bulkAdd(added)'))
check('orphan attachment cleanup exists',attachmentService.includes('cleanupOrphans'))
check('full backup serializes binary attachments',backup.includes('serializeAttachment')&&backup.includes('deserializeAttachment')&&backup.includes('d.attachments'))
check('selective export includes attachments',selective.includes('portableAttachments')&&selective.includes('notes: selectedNotes'))
check('content search indexes attachment metadata',search.includes('attachmentIndex')&&search.includes('rebuildOwner'))
check('content search self-heals direct task writes',search.includes('async ensureFresh()')&&search.includes('ownerStale'))
check('rich content stylesheet loaded',styles.includes("@import './notes-rich-content.css';")&&exists('src/styles/notes-rich-content.css'))
check('public v21 backup schema exists',exists('public/schema/folio-backup-v21.schema.json'))
check('D9 documentation exists',exists('docs/NOTES_RICH_CONTENT_D9.md'))

const failures=checks.filter((item)=>!item.ok)
for(const item of checks) console.log(`${item.ok?'PASS':'FAIL'}  ${item.name}`)
console.log(`\n${checks.length-failures.length}/${checks.length} D9 checks passed.`)
if(failures.length) process.exit(1)
