import fs from 'node:fs'
import path from 'node:path'

const root=process.cwd()
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8')
const exists=(p)=>fs.existsSync(path.join(root,p))
const checks=[]
const check=(name,ok)=>checks.push({name,ok:Boolean(ok)})

const pkg=JSON.parse(read('package.json'))
const models=read('src/domain/models.ts')
const database=read('src/db/database.ts')
const logic=read('src/features/analytics/analyticsLogic.ts')
const hook=read('src/hooks/useAnalyticsData.ts')
const view=read('src/features/analytics/AnalyticsView.tsx')
const app=read('src/app/App.tsx')
const uiTypes=read('src/types/ui.ts')
const sidebar=read('src/components/layout/Sidebar.tsx')
const mobile=read('src/components/layout/MobileMoreSheet.tsx')
const icon=read('src/components/ui/Icon.tsx')
const styles=read('src/styles/analytics-v2.css')
const styleIndex=read('src/styles/index.css')

check('D12 validator registered',pkg.scripts?.['validate:d12']==='node scripts/validate-analytics-d12.mjs')
check('release gate runs D12',pkg.scripts?.['release:verify']?.includes('validate:d12'))
check('D12 remains derived on schema v23',/DATABASE_SCHEMA_VERSION\s*=\s*23\b/.test(database)&&!database.includes('this.version(24)'))
check('analytics does not add persistent entity models',!models.includes('AnalyticsEntity')&&!models.includes('StatisticEntity'))
check('analytics engine exists',logic.includes('buildAnalyticsSnapshot')&&logic.includes('AnalyticsPeriodSummary'))
check('same-length previous period comparison exists',logic.includes('previousThrough')&&logic.includes('previousFrom')&&logic.includes('previousSummary'))
check('completion trend exists',logic.includes('completedTasks')&&logic.includes('weeklyRows'))
check('planned versus completed exists',logic.includes('plannedTasks')&&logic.includes('plannedCompleted')&&logic.includes('planCompletionRate'))
check('overdue rate exists',logic.includes('overdueRate')&&logic.includes('dueTasks')&&logic.includes('overdueTasks'))
check('estimate versus actual exists',logic.includes('calibrationRows')&&logic.includes('estimateMinutes')&&logic.includes('actualMinutes'))
check('focus totals include manual provenance',logic.includes('focusSeconds')&&logic.includes('manualFocusSeconds'))
check('habit adherence and streak analytics exist',logic.includes('habitAdherence')&&logic.includes('habitCurrentStreak')&&logic.includes('habitBestStreak'))
check('project velocity exists',logic.includes('velocityPerWeek')&&logic.includes('projectRows'))
check('workload analytics uses plan capacity',logic.includes('capacityMinutes')&&logic.includes('workloadPercent')&&logic.includes('overloadedDays'))
check('weekday patterns exist',logic.includes('weekdayRows')&&logic.includes('weekdayLabels'))
check('time-of-day patterns exist',logic.includes('timeBucket')&&logic.includes('Morning · 06–12')&&logic.includes('Evening · 18–22'))
check('monthly and yearly report aggregation exists',logic.includes("mode:'month'|'year'")&&logic.includes("reportRows(input,daily,fromDate,throughDate,'month')")&&logic.includes("reportRows(input,daily,fromDate,throughDate,'year')"))
check('deleted completed tasks remain historical evidence',logic.includes('function rootTask')&&logic.includes('currentlyRelevantTask'))
check('analytics hook uses repositories only',hook.includes('taskRepository.listSnapshot')&&hook.includes('focusSessionRepository.listAll')&&hook.includes('habitRepository.listAllEntries')&&!hook.includes("from '../db/database'"))
check('analytics workspace has range presets',view.includes('30 days')&&view.includes('90 days')&&view.includes('12 months')&&view.includes('This year'))
check('analytics workspace surfaces KPI scoreboard',view.includes('analytics-scoreboard')&&view.includes('Same-day plan execution')&&view.includes('Overdue rate')&&view.includes('Estimate variance'))
check('analytics workspace surfaces project habit and pattern sections',view.includes('Project velocity')&&view.includes('Habit consistency')&&view.includes('Time-of-day'))
check('analytics workspace surfaces monthly and yearly reports',view.includes('Monthly report')&&view.includes('Yearly report'))
check('Analytics navigation type exists',uiTypes.includes("'analytics'"))
check('desktop navigation exposes Analytics',sidebar.includes("view: 'analytics'")&&sidebar.includes("icon: 'analytics'"))
check('mobile navigation exposes Analytics',mobile.includes("view: 'analytics'"))
check('analytics icon exists',icon.includes("analytics:")&&icon.includes("'analytics'"))
check('App routes Analytics workspace',app.includes("view === 'analytics'")&&app.includes('<AnalyticsView'))
check('command palette exposes Analytics',app.includes("id: 'nav-analytics'")&&app.includes("navigate('analytics')"))
check('go chord exposes Analytics',app.includes("a: 'analytics'")&&app.includes('A Analytics'))
check('analytics stylesheet loaded',styleIndex.includes("@import './analytics-v2.css';")&&styles.includes('D12 — Statistics & Analytics'))
check('D12 documentation exists',exists('docs/STATISTICS_ANALYTICS_D12.md'))

const failures=checks.filter((item)=>!item.ok)
for(const item of checks)console.log(`${item.ok?'PASS':'FAIL'}  ${item.name}`)
console.log(`\n${checks.length-failures.length}/${checks.length} D12 checks passed.`)
if(failures.length)process.exit(1)
