import fs from 'node:fs'
import path from 'node:path'

const root=process.cwd()
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8')
const exists=(p)=>fs.existsSync(path.join(root,p))
const checks=[]
const check=(name,ok)=>checks.push({name,ok:Boolean(ok)})

const pkg=JSON.parse(read('package.json'))
const models=read('src/domain/models.ts')
const schemas=read('src/domain/schemas.ts')
const database=read('src/db/database.ts')
const migration=read('src/migrations/v21ToV22.ts')
const domain=read('src/domain/habit.ts')
const repo=read('src/repositories/habitRepository.ts')
const groups=read('src/repositories/habitGroupRepository.ts')
const templates=read('src/repositories/habitTemplateRepository.ts')
const editor=read('src/features/habits/HabitEditorModal.tsx')
const view=read('src/features/habits/HabitsView.tsx')
const detail=read('src/features/habits/HabitDetailDrawer.tsx')
const reminderUi=read('src/features/reminders/HabitReminderSection.tsx')
const reminderEngine=read('src/services/reminderEngine.ts')
const backup=read('src/services/backupService.ts')
const backupSchemas=read('src/services/backupSchemas.ts')
const importer=read('src/features/import/importSchema.ts')
const patcher=read('src/features/patch/patchSchema.ts')
const publicImport=read('public/schema/folio-import-v1.schema.json')
const publicPatch=read('public/schema/folio-patch-v1.schema.json')
const interop=read('src/features/interop/InteroperabilityModal.tsx')
const app=read('src/app/App.tsx')
const styles=read('src/styles/habits-focus.css')

check('D10 validator registered',pkg.scripts?.['validate:d10']==='node scripts/validate-habits-v2-d10.mjs')
check('release gate runs D10',pkg.scripts?.['release:verify']?.includes('validate:d10'))
check('D10 remains schema-compatible',Number(database.match(/DATABASE_SCHEMA_VERSION\s*=\s*(\d+)/)?.[1]??0)>=22&&database.includes('this.version(22)'))
check('v21 to v22 migration registered',database.includes('migrateV21ToV22')&&migration.includes("tx.table('habits')"))
check('quantity habit kind exists',models.includes("'quantity'")&&schemas.includes("'quantity'"))
check('monthly frequency exists',models.includes("'times-per-month'")&&schemas.includes("'times-per-month'")&&schemas.includes('timesPerMonth'))
check('habit color unit and grouping persist',models.includes('unit?: string')&&models.includes('color?: string')&&models.includes('groupId?: EntityId'))
check('habit group model exists',models.includes('interface HabitGroupEntity')&&groups.includes('habitGroupRepository'))
check('habit template model and builtins exist',models.includes('interface HabitTemplateEntity')&&templates.includes('BUILTIN_HABIT_TEMPLATES'))
check('historical values are editable and uncapped',repo.includes('putEntry')&&domain.includes('habitHistoryStatus')&&detail.includes('Edit history'))
check('historical clear action exists',detail.includes('onHistoryClear')&&app.includes('habitService.clearEntry'))
check('12-week trend and heatmap exist',detail.includes('12-week trend')&&detail.includes('12-week heatmap')&&domain.includes('habitWeeklyTrend'))
check('best streak and 90-day adherence exist',domain.includes('habitBestStreak')&&domain.includes('adherence90'))
check('monthly and weekly period progress exist',domain.includes('habitPeriodProgress')&&domain.includes('weeklyTarget'))
check('editor exposes quantity monthly group and color',editor.includes('Quantity')&&editor.includes('Flexible times per month')&&editor.includes('Group')&&editor.includes('type="color"'))
check('Habits view renders groups and templates entry point',view.includes('grouped.map')&&view.includes('Templates')&&view.includes('onGroups'))
check('App wires group and template drawers',app.includes('<HabitGroupsDrawer')&&app.includes('<HabitTemplatesDrawer')&&app.includes('habitInputFromTemplate'))
check('flexible reminder prompt days exist',reminderUi.includes('Prompt days')&&reminderUi.includes('times-per-month'))
check('reminder engine respects flexible prompts and pauses',reminderEngine.includes('habitReminderDateEligible')&&reminderEngine.includes('habitPausedForDate'))
check('backup schemas preserve quantity monthly groups templates',backupSchemas.includes("'quantity'")&&backupSchemas.includes("'times-per-month'")&&backupSchemas.includes('backupHabitGroupSchema')&&backupSchemas.includes('backupHabitTemplateSchema'))
check('backup envelope includes Habit V2 tables',backup.includes('habitGroups: HabitGroupEntity[]')&&backup.includes('habitTemplates: HabitTemplateEntity[]')&&backup.includes('db.habitGroups.bulkPut'))
check('structured import supports quantity monthly habits',importer.includes("'quantity'")&&importer.includes("'times-per-month'")&&importer.includes('unit:'))
check('structured patch supports quantity monthly habits',patcher.includes("'quantity'")&&patcher.includes('unit:'))
check('public import advertises quantity monthly habits',publicImport.includes('"quantity"')&&publicImport.includes('"times-per-month"')&&publicImport.includes('"timesPerMonth"'))
check('public patch advertises quantity monthly habits',publicPatch.includes('"quantity"')&&publicPatch.includes('"times-per-month"')&&publicPatch.includes('"timesPerMonth"'))
check('public v22 backup schema exists',exists('public/schema/folio-backup-v22.schema.json'))
check('interop preserves D10 backup compatibility',interop.includes('Schema v23 · complete planner state + rich content + Habits V2 + Focus V2')&&interop.includes('schema v8–v23'))
check('Habit V2 styles exist',styles.includes('D10 — Habits V2')&&styles.includes('habit-history-grid--v2')&&styles.includes('habit-template-list'))
check('D10 documentation exists',exists('docs/HABITS_V2_D10.md'))

const failures=checks.filter((item)=>!item.ok)
for(const item of checks) console.log(`${item.ok?'PASS':'FAIL'}  ${item.name}`)
console.log(`\n${checks.length-failures.length}/${checks.length} D10 checks passed.`)
if(failures.length) process.exit(1)
