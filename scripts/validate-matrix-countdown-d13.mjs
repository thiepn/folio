import fs from 'node:fs'
import path from 'node:path'

const root=process.cwd()
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8')
const exists=(p)=>fs.existsSync(path.join(root,p))
const checks=[]
const check=(name,ok)=>checks.push({name,ok:Boolean(ok)})

const pkg=JSON.parse(read('package.json'))
const database=read('src/db/database.ts')
const logic=read('src/features/matrix/matrixCountdownLogic.ts')
const view=read('src/features/matrix/MatrixCountdownView.tsx')
const app=read('src/app/App.tsx')
const uiTypes=read('src/types/ui.ts')
const sidebar=read('src/components/layout/Sidebar.tsx')
const mobile=read('src/components/layout/MobileMoreSheet.tsx')
const mobileNav=read('src/components/layout/MobileNav.tsx')
const icon=read('src/components/ui/Icon.tsx')
const styles=read('src/styles/matrix-countdown-v2.css')
const styleIndex=read('src/styles/index.css')

check('D13 validator registered',pkg.scripts?.['validate:d13']==='node scripts/validate-matrix-countdown-d13.mjs')
check('release gate runs D13',pkg.scripts?.['release:verify']?.includes('validate:d13'))
check('D13 remains derived on schema v23',/DATABASE_SCHEMA_VERSION\s*=\s*23\b/.test(database)&&!database.includes('this.version(24)'))
check('matrix logic exists',logic.includes('buildMatrix')&&logic.includes('MatrixQuadrant'))
check('importance maps to existing priority',logic.includes("task.priority === 'high' || task.priority === 'critical'"))
check('urgency uses deadline horizon and planned date',logic.includes('deadline')&&logic.includes('horizonDays')&&logic.includes('task.plannedDate <= today'))
check('matrix has four quadrants',logic.includes("'do' | 'schedule' | 'delegate' | 'later'")&&view.includes('Do now')&&view.includes('Schedule')&&view.includes('Quick / delegate')&&view.includes('Later / reconsider'))
check('urgency horizon controls exist',view.includes('Urgency horizon')&&view.includes('[0, 3, 7, 14]'))
check('matrix actions mutate existing task fields',app.includes('onSetImportant')&&app.includes("taskService.update(id, { priority })")&&app.includes('onPlanToday')&&app.includes("moveToDate(id, 'today'"))
check('matrix completion remains undoable',app.includes("taskService.setCompleted(id, true).then(registerUndo)"))
check('countdown logic combines task and project deadlines',logic.includes("kind: 'task'")&&logic.includes("kind: 'project'"))
check('countdown includes exams',logic.includes("kind: 'exam'")&&logic.includes('project.examDate'))
check('countdown includes incomplete milestones',logic.includes("kind: 'milestone'")&&logic.includes('milestone.completedAt'))
check('countdown pressure bands exist',logic.includes("'overdue' | 'today' | 'week' | 'month' | 'later'")&&view.includes('Next 7d')&&view.includes('8–30d'))
check('countdown has range filters',view.includes("([7, 30, 90, 365, 'all'] as CountdownRange[])"))
check('countdown has entity-type filters',view.includes('<option value="task">Tasks</option>')&&view.includes('<option value="exam">Exams</option>')&&view.includes('<option value="milestone">Milestones</option>'))
check('countdown items open owning task/project',view.includes("if (item.kind === 'task') onOpenTask")&&view.includes('else onOpenProject'))
check('project urgency pressure strip exists',view.includes('Urgent project pressure')&&view.includes('projectPressure'))
check('Matrix navigation type exists',uiTypes.includes("'matrix'"))
check('desktop navigation exposes Matrix',sidebar.includes("view: 'matrix'")&&sidebar.includes("icon: 'matrix'"))
check('mobile navigation exposes Matrix',mobile.includes("view: 'matrix'")&&mobileNav.includes("active === 'matrix'"))
check('matrix icon exists',icon.includes("matrix:")&&icon.includes("'matrix'"))
check('App routes Matrix workspace',app.includes("view === 'matrix'")&&app.includes('<MatrixCountdownView'))
check('command palette exposes Matrix',app.includes("id: 'nav-matrix'")&&app.includes("navigate('matrix')"))
check('go chord exposes Matrix',app.includes("m: 'matrix'")&&app.includes('M Matrix'))
check('matrix stylesheet loaded',styleIndex.includes("@import './matrix-countdown-v2.css';")&&styles.includes('D13 — Matrix / Countdown'))
check('D13 documentation exists',exists('docs/MATRIX_COUNTDOWN_D13.md'))

const failures=checks.filter((item)=>!item.ok)
for(const item of checks)console.log(`${item.ok?'PASS':'FAIL'}  ${item.name}`)
console.log(`\n${checks.length-failures.length}/${checks.length} D13 checks passed.`)
if(failures.length)process.exit(1)
