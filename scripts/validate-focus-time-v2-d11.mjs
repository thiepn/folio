import fs from 'node:fs'
import path from 'node:path'

const root=process.cwd()
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8')
const exists=(p)=>fs.existsSync(path.join(root,p))
const checks=[]
const check=(name,ok)=>checks.push({name,ok:Boolean(ok)})

const pkg=JSON.parse(read('package.json'))
const models=read('src/domain/models.ts')
const schemas=read('src/domain/schemas.ts')
const database=read('src/db/database.ts')
const migration=read('src/migrations/v22ToV23.ts')
const logic=read('src/features/focus/focusLogic.ts')
const repo=read('src/repositories/focusSessionRepository.ts')
const service=read('src/services/focusService.ts')
const settings=read('src/services/focusSettingsService.ts')
const hook=read('src/hooks/useFocusData.ts')
const overlay=read('src/features/focus/FocusOverlay.tsx')
const mini=read('src/features/focus/FocusMiniTimer.tsx')
const history=read('src/features/focus/FocusHistoryDrawer.tsx')
const app=read('src/app/App.tsx')
const reviewLogic=read('src/features/review/reviewLogic.ts')
const reviewHook=read('src/hooks/useReviewData.ts')
const reviewView=read('src/features/review/ReviewView.tsx')
const historyLogic=read('src/features/review/historyLogic.ts')
const backupSchemas=read('src/services/backupSchemas.ts')
const interop=read('src/features/interop/InteroperabilityModal.tsx')
const styles=read('src/styles/habits-focus.css')

check('D11 validator registered',pkg.scripts?.['validate:d11']==='node scripts/validate-focus-time-v2-d11.mjs')
check('release gate runs D11',pkg.scripts?.['release:verify']?.includes('validate:d11'))
check('database schema v23',/DATABASE_SCHEMA_VERSION\s*=\s*23\b/.test(database)&&database.includes('this.version(23)'))
check('v22 to v23 focus migration registered',database.includes('migrateV22ToV23')&&migration.includes("tx.table('focusSessions')"))
check('focus mode supports pomodoro',models.includes("FocusMode = 'stopwatch' | 'countdown' | 'pomodoro'")&&schemas.includes("'pomodoro'"))
check('focus provenance supports manual and timer',models.includes("FocusSessionSource = 'timer' | 'manual'")&&schemas.includes("'manual'"))
check('Pomodoro cycle model exists',models.includes('interface FocusCycleSettings')&&models.includes("FocusPhase = 'focus' | 'short-break' | 'long-break'"))
check('focus sessions store tags context interruptions and break time',models.includes('context?: string')&&models.includes('tags: string[]')&&models.includes('interruptionCount: number')&&models.includes('breakSeconds: number'))
check('focus logic separates focus and break time',logic.includes('effectiveBreakSeconds')&&logic.includes("(session.phase ?? 'focus') !== 'focus'")&&logic.includes('focusPhaseTargetSeconds'))
check('repository supports finished session editing',repo.includes('editFinished')&&repo.includes('listFinishedBetween'))
check('service supports manual time entries',service.includes('async createManual')&&service.includes("source:'manual'"))
check('service supports undoable edits and deletes',service.includes('async editFinished')&&service.includes('async removeFinished')&&service.includes("message:'Focus session deleted'"))
check('service supports explicit interruptions',service.includes('async interrupt')&&service.includes('interruptionCount'))
check('service supports Pomodoro phase transitions',service.includes('async completePhase')&&service.includes("'long-break'")&&service.includes("'short-break'"))
check('reload/background reconcile caps timed sessions',service.includes('async reconcileActive')&&service.includes('countdownReached'))
check('goals and reusable presets exist',settings.includes('DEFAULT_FOCUS_GOALS')&&settings.includes('BUILTIN_FOCUS_TEMPLATES')&&settings.includes('saveTemplate'))
check('focus hook exposes daily trend and breakdowns',hook.includes('dailyTrend')&&hook.includes('projectBreakdown')&&hook.includes('taskBreakdown'))
check('focus hook exposes goal progress',hook.includes('dailyGoalPercent')&&hook.includes('weeklyGoalPercent'))
check('launcher exposes Pomodoro and custom cycles',overlay.includes('Pomodoro')&&overlay.includes('focus-cycle-editor')&&overlay.includes('cyclesBeforeLongBreak'))
check('launcher supports context tags and presets',overlay.includes('Context')&&overlay.includes('Tags')&&overlay.includes('Save preset'))
check('focus keyboard controls exist',overlay.includes("event.code==='Space'")&&overlay.includes("event.key.toLowerCase()==='i'")&&overlay.includes("event.shiftKey&&event.key==='Enter'"))
check('persistent mini timer exists',mini.includes('FocusMiniTimer')&&mini.includes('focusDisplaySeconds')&&mini.includes("if(reached&&session.status==='running')"))
check('manual time log UI exists',history.includes('Manual time entry')&&history.includes('Add time'))
check('finished sessions can edit and delete in UI',history.includes('Session history')&&history.includes('beginEdit')&&history.includes('Delete this focus session?'))
check('analytics UI includes 14-day project and estimate views',history.includes('14-day focus')&&history.includes('Projects · this week')&&history.includes('Tasks · actual vs estimate'))
check('App wires Focus V2 surfaces',app.includes('<FocusMiniTimer')&&app.includes('<FocusHistoryDrawer')&&app.includes('focusService.completePhase')&&app.includes('focusService.createManual'))
check('App reconciles focus on visibility and pageshow',app.includes("addEventListener('pageshow'")&&app.includes("visibilitychange")&&app.includes('focusService.reconcileActive'))
check('Review contains interruptions manual time and goal progress',reviewLogic.includes('focusInterruptionCount')&&reviewLogic.includes('manualFocusSeconds')&&reviewLogic.includes('focusGoalPercent')&&reviewHook.includes('focusSettingsService.getGoals')&&reviewView.includes('Weekly focus goal'))
check('history search indexes focus context and tags',historyLogic.includes('session.context')&&historyLogic.includes('...(session.tags ?? [])'))
check('backup schema preserves D11 focus metadata',backupSchemas.includes("'pomodoro'")&&backupSchemas.includes("source: z.enum(['timer','manual'])")&&backupSchemas.includes('interruptionCount')&&backupSchemas.includes('breakSeconds'))
check('public v23 backup schema exists',exists('public/schema/folio-backup-v23.schema.json'))
check('interop advertises schema v23',interop.includes('Schema v23 · complete planner state + rich content + Habits V2 + Focus V2')&&interop.includes('schema v8–v23'))
check('D11 visual system exists',styles.includes('D11 — Focus & Time Tracking V2')&&styles.includes('focus-mini-timer')&&styles.includes('focus-history-v2'))
check('D11 documentation exists',exists('docs/FOCUS_TIME_V2_D11.md'))

const failures=checks.filter((item)=>!item.ok)
for(const item of checks) console.log(`${item.ok?'PASS':'FAIL'}  ${item.name}`)
console.log(`\n${checks.length-failures.length}/${checks.length} D11 checks passed.`)
if(failures.length)process.exit(1)
