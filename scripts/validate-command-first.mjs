import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const exists = (p) => fs.existsSync(path.join(root, p))
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const database = read('src/db/database.ts')
const palette = read('src/features/power/CommandPalette.tsx')
const shortcuts = read('src/features/power/shortcuts.ts')
const help = read('src/features/power/ShortcutHelpModal.tsx')
const builders = read('src/features/power/commandBuilders.ts')
const topbar = read('src/components/layout/Topbar.tsx')
const app = read('src/app/App.tsx')
const styles = read('src/styles/index.css')

check('v1.7 package version', pkg.version === '1.7.0')
check('command-first validator registered', pkg.scripts?.['validate:command-first'] === 'node scripts/validate-command-first.mjs')
check('release gate runs command-first validation', pkg.scripts?.['release:verify']?.includes('validate:command-first'))
check('schema v15 retained', /DATABASE_SCHEMA_VERSION\s*=\s*15\b/.test(database) && !database.includes('this.version(16)'))
check('palette supports nested commands', palette.includes('children?: PowerCommand[]') && palette.includes('collectCommandPaths'))
check('palette stores recent commands locally', palette.includes("folio:command-recents:v1") && palette.includes('persistRecentCommandIds'))
check('recent commands do not require database state', !palette.includes('settingsRepository') && !palette.includes('db.'))
check('palette has fuzzy subsequence matching', palette.includes('subsequencePenalty') && palette.includes('scorePath'))
check('nested search includes parent labels', palette.includes("entry.parents.map((parent) => parent.label)") && palette.includes('parentLabels'))
check('palette supports scoped back navigation', palette.includes('scopeStack') && palette.includes('goBack()') && palette.includes("event.key === 'Backspace'"))
check('palette supports Home and End navigation', palette.includes("event.key === 'Home'") && palette.includes("event.key === 'End'"))
check('palette exposes active descendant accessibility', palette.includes('aria-activedescendant'))
check('reserved command-first aliases exist', shortcuts.includes("'n', 'p', 't', '/'") || (shortcuts.includes("'n'") && shortcuts.includes("'p'") && shortcuts.includes("'t'") && shortcuts.includes("'/'")))
check('shortcut help documents command aliases', help.includes("['/', 'Open command palette / search']") && help.includes("['N', 'New task in the current context']") && help.includes("['P', 'New project']") && help.includes("['T', 'Go straight to Today']"))
check('topbar describes search as command surface', topbar.includes('Search or command') && topbar.includes('Ctrl/⌘ K · /'))
check('task command builder exists', builders.includes('buildTaskCommandChildren') && builders.includes('TaskPreview'))
check('project command builder exists', builders.includes('buildProjectCommandChildren'))
check('habit command builder exists', builders.includes('buildHabitCommandChildren'))
check('app imports command builders', app.includes('buildTaskCommandChildren') && app.includes('buildProjectCommandChildren') && app.includes('buildHabitCommandChildren'))
check('fixed slash alias opens palette', app.includes("key === '/'" ) && app.includes('setPaletteOpen(true)'))
check('fixed N alias creates contextual task', app.includes("key === 'n'") && app.includes('openAdd('))
check('fixed P alias creates project', app.includes("key === 'p'") && app.includes('setProjectEditorOpen(true)'))
check('fixed T alias navigates Today', app.includes("key === 't'") && app.includes("navigate('today')"))
check('go chord resolves before fixed aliases', app.includes("if (next) { event.preventDefault(); navigate(next); return }") )
check('new project command exists', app.includes("id: 'create-project'") && app.includes("label: 'New project'"))
check('new habit command exists', app.includes("id: 'create-habit'") && app.includes("label: 'New habit'"))
check('task open command exists', app.includes("label: 'Open task…'"))
check('task completion commands exist', app.includes("label: 'Complete task…'") && app.includes("label: 'Reopen task…'"))
check('task horizon commands exist', app.includes("label: 'Move task to Today…'") && app.includes("label: 'Move task to Tomorrow…'") && app.includes("label: 'Move task to Later…'"))
check('focus task command exists', app.includes("label: 'Start Focus on task…'"))
check('project and habit open commands exist', app.includes("label: 'Open project…'") && app.includes("label: 'Open habit…'"))
check('habit action commands exist', app.includes("label: 'Complete habit today…'") && app.includes("label: 'Skip habit today…'"))
check('workspace search-only entities remain', app.includes('searchOnly: true') && palette.includes('searchOnly?: boolean'))
check('mobile command access exists', app.includes('mobile-command-button') && app.includes('Search'))
check('command-first stylesheet loaded', styles.includes("@import './command-first.css';"))
check('command-first release doc exists', exists('docs/COMMAND_FIRST_UX_V1_7.md'))

const failures = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'}  ${item.name}`)
console.log(`\n${checks.length - failures.length}/${checks.length} command-first checks passed.`)
if (failures.length) process.exit(1)
