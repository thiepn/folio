import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const exists = (p) => fs.existsSync(path.join(root, p))
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const models = read('src/domain/models.ts')
const schemas = read('src/domain/schemas.ts')
const database = read('src/db/database.ts')
const migration = read('src/migrations/v12ToV13.ts')
const repository = read('src/repositories/projectRepository.ts')
const service = read('src/services/projectService.ts')
const detail = read('src/features/projects/ProjectDetailView.tsx')
const editor = read('src/features/projects/ProjectEditorModal.tsx')
const projects = read('src/features/projects/ProjectsView.tsx')
const app = read('src/app/App.tsx')
const styles = read('src/styles/index.css')

check('v1.3+ package version', Number(pkg.version.split('.')[1] ?? 0) >= 3)
check('task-project validator registered', pkg.scripts?.['validate:task-project'] === 'node scripts/validate-task-project-workflow.mjs')
check('release gate runs task-project validation', pkg.scripts?.['release:verify']?.includes('validate:task-project'))
check('task-project compatible schema', Number(database.match(/DATABASE_SCHEMA_VERSION\s*=\s*(\d+)/)?.[1] ?? 0) >= 13)
check('v12 to v13 migration registered', database.includes('migrateV12ToV13') && database.includes('this.version(13)'))
check('migration initializes project workflow state', migration.includes("project.status = 'active'") && migration.includes("project.notes = ''") && migration.includes('project.milestones = []'))
check('project model has execution fields', models.includes('ProjectStatus') && models.includes('nextActionTaskId') && models.includes('ProjectMilestone') && models.includes('ProjectActivityEntry'))
check('project schemas validate execution fields', schemas.includes('projectStatusSchema') && schemas.includes('nextActionTaskId') && schemas.includes('deadline: localDate'))
check('project progress is derived', repository.includes('progressPercent') && repository.includes('summary.completed / total'))
check('next action is explicit or derived', repository.includes('nextTaskForProject') && service.includes('setNextAction'))
check('milestone services are undoable', service.includes('addMilestone') && service.includes('toggleMilestone') && service.includes('removeMilestone') && service.includes('undo: async'))
check('project detail has filters and quick actions', detail.includes("type TaskFilter = 'open' | 'ready' | 'blocked' | 'completed' | 'all'") && detail.includes('Move to Today') && detail.includes('Set as next action'))
check('project detail renders milestones and history', detail.includes('title="Milestones"') && detail.includes('Project history'))
check('project editor exposes status deadline and notes', editor.includes('<span>Status</span>') && editor.includes('Project deadline') && editor.includes('Context / notes'))
check('project cards expose workflow state', projects.includes('project.progressPercent') && projects.includes('project.nextActionTitle') && projects.includes('project-status'))
check('app wires project workflow actions', app.includes('projectService.setNextAction') && app.includes('projectService.addMilestone') && app.includes('onTaskMove'))
check('workflow stylesheet loaded', styles.includes("@import './task-project-workflow.css';"))
check('backup v13 schema exists', exists('public/schema/folio-backup-v13.schema.json'))
check('v1.3 release doc exists', exists('docs/TASK_PROJECT_WORKFLOW_V1_3.md'))

const failures = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'}  ${item.name}`)
console.log(`\n${checks.length - failures.length}/${checks.length} task-project checks passed.`)
if (failures.length) process.exit(1)
